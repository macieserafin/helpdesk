create table attachments (
    id bigint generated by default as identity primary key,
    ticket_id bigint not null,
    comment_id bigint,
    uploaded_by_id bigint not null,
    file_name varchar(255) not null,
    file_path varchar(500) not null,
    content_type varchar(100),
    file_size bigint,
    uploaded_at timestamp(6) not null
);

create table categories (
    id bigint generated by default as identity primary key,
    name varchar(100) not null unique,
    description text,
    active boolean not null,
    created_at timestamp(6) not null
);

create table comments (
    id bigint generated by default as identity primary key,
    ticket_id bigint not null,
    author_id bigint not null,
    content text not null,
    internal boolean not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6)
);

create table roles (
    id bigint generated by default as identity primary key,
    name varchar(30) not null unique
);

create table tickets (
    id bigint generated by default as identity primary key,
    title varchar(150) not null,
    description text not null,
    status varchar(30) not null,
    priority varchar(30) not null,
    created_by_id bigint not null,
    assigned_to_id bigint,
    category_id bigint not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6),
    resolved_at timestamp(6),
    closed_at timestamp(6)
);

create table ticket_history (
    id bigint generated by default as identity primary key,
    ticket_id bigint not null,
    changed_by_id bigint not null,
    action_type varchar(50) not null,
    old_status varchar(30),
    new_status varchar(30),
    old_priority varchar(30),
    new_priority varchar(30),
    old_assigned_to_id bigint,
    new_assigned_to_id bigint,
    note text,
    changed_at timestamp(6) not null
);

create table users (
    id bigint generated by default as identity primary key,
    login_identifier varchar(50) not null unique,
    email varchar(100) not null unique,
    email_verified boolean not null,
    email_verified_at timestamp(6),
    two_factor_enabled boolean not null,
    notifications_enabled boolean not null,
    password_hash varchar(255) not null,
    enabled boolean not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6)
);

create table user_profiles (
    id bigint generated by default as identity primary key,
    first_name varchar(50),
    last_name varchar(50),
    phone_number varchar(30),
    city varchar(100),
    street_address varchar(150),
    postal_code varchar(20),
    user_id bigint not null unique
);

create table user_roles (user_id bigint not null references users(id), role_id bigint not null references roles(id), primary key (user_id, role_id));

