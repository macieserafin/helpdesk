alter table comments add foreign key (author_id) references users(id);

alter table tickets add foreign key (created_by_id) references users(id);

alter table tickets add foreign key (assigned_to_id) references users(id);

alter table tickets add foreign key (category_id) references categories(id);

alter table ticket_history add foreign key (ticket_id) references tickets(id);

alter table ticket_history add foreign key (changed_by_id) references users(id);

alter table ticket_history add foreign key (old_assigned_to_id) references users(id);

alter table ticket_history add foreign key (new_assigned_to_id) references users(id);

alter table user_profiles add foreign key (user_id) references users(id);
